"""Dependency boundaries consumed by orchestration."""

from typing import Protocol

from forj_review_config_service.contracts.models import TaskRecord


class Conversation(Protocol):
    async def complete(self, messages: list[dict], tools: list[dict]) -> dict: ...

    async def analyze(self, samples: list[dict], focus: str) -> dict: ...


class ConfigurationKernel(Protocol):
    def page_options(self, draft: dict) -> dict: ...

    def edit_fields(self, draft: dict, operations: list[dict]) -> dict: ...

    def field_dependencies(self, draft: dict) -> dict: ...

    def comparison_configurable_fields(self, draft: dict) -> list[str]: ...

    def evaluate_collection(
        self, manifest, facts, page_id, reference_samples, sample_mapping
    ) -> dict: ...

    def proof_is_current(self, proof: dict) -> bool: ...

    async def baseline(self, page_id: str | None = None) -> str: ...

    async def context(self, page_id: str | None = None) -> dict: ...

    async def capabilities(self) -> dict: ...

    async def read_cases(self, case_set_id: str) -> dict: ...

    async def rollback_draft(self, page_id: str, version: str) -> dict: ...

    async def template_members(self, reference: dict | None) -> dict: ...

    async def validate(self, record: TaskRecord) -> dict: ...

    async def replay(self, record: TaskRecord, case_set_id: str) -> dict: ...

    async def verify_replay_receipt(self, result: dict) -> bool: ...

    async def commit(self, record: TaskRecord, operation_id: str) -> dict: ...

    async def commit_receipt(self, operation_id: str) -> dict | None: ...

    async def activation(self, record: TaskRecord) -> dict: ...
