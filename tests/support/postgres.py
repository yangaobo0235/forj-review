"""Synthetic schemas for isolated PostgreSQL tests; never used by application startup."""

from contextlib import contextmanager
from uuid import uuid4

import psycopg
from langgraph.checkpoint.postgres import PostgresSaver
from psycopg import sql

from forj_review_config_service.integrations.database import Database
from forj_review_service.integrations.engine_emissions import create_reference_table


def initialize(database):
    with database.connect() as db:
        if not db.execute("SELECT 1 FROM pg_namespace WHERE nspname=%s", (database.schema,)).fetchone():
            db.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(database.schema)))
        db.execute("CREATE TABLE IF NOT EXISTS storage_version(version INTEGER PRIMARY KEY)")
        versions = db.execute("SELECT version FROM storage_version").fetchall()
        if versions and versions != [(2,)]:
            raise ValueError("数据库存储版本不兼容，请使用匹配的程序")
        db.execute("INSERT INTO storage_version VALUES(2) ON CONFLICT DO NOTHING")
        create_reference_table(db)
        db.execute("""CREATE TABLE IF NOT EXISTS page_snapshots(
            id INTEGER PRIMARY KEY CHECK(id=1), files JSONB NOT NULL,
            revision BIGINT NOT NULL DEFAULT 1)""")
        db.execute("""CREATE TABLE IF NOT EXISTS sessions(
            id TEXT PRIMARY KEY, body JSONB NOT NULL,
            position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE)""")
        db.execute("""CREATE TABLE IF NOT EXISTS captures(
            id TEXT PRIMARY KEY, body JSONB NOT NULL,
            position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE)""")
        db.execute("""CREATE TABLE IF NOT EXISTS events(
            seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            session_id TEXT NOT NULL, kind TEXT NOT NULL, body JSONB NOT NULL)""")
        db.execute("CREATE INDEX IF NOT EXISTS events_session ON events(session_id,seq)")
        db.execute("""CREATE TABLE IF NOT EXISTS requests(
            scope TEXT NOT NULL, id TEXT NOT NULL, fingerprint TEXT NOT NULL,
            result JSONB NOT NULL, PRIMARY KEY(scope,id))""")
        # JSONB holds evolving workflow documents; stored generated columns expose
        # relational keys and status without introducing two writable sources.
        db.execute("""ALTER TABLE sessions
            ADD COLUMN capture_id TEXT GENERATED ALWAYS AS (NULLIF(body->>'capture_id','')) STORED,
            ADD COLUMN state TEXT GENERATED ALWAYS AS (body->>'state') STORED,
            ADD COLUMN turn_status TEXT GENERATED ALWAYS AS (body->>'turn_status') STORED,
            ADD COLUMN revision BIGINT GENERATED ALWAYS AS ((body->>'revision')::bigint) STORED,
            ADD CONSTRAINT ck_sessions_body_object CHECK(jsonb_typeof(body)='object'),
            ADD CONSTRAINT ck_sessions_document_id CHECK((body->>'session_id') IS NOT DISTINCT FROM id),
            ADD CONSTRAINT ck_sessions_revision CHECK(revision IS NOT NULL AND revision>=0),
            ADD CONSTRAINT ck_sessions_state CHECK(state IS NOT NULL AND state IN
                ('DRAFTING','NEEDS_INPUT','READY_FOR_CONFIRMATION','SAVED_PENDING_RESTART','EFFECTIVE','BLOCKED')),
            ADD CONSTRAINT ck_sessions_turn_status CHECK(turn_status IS NOT NULL AND turn_status IN
                ('COMPLETED','RUNNING','QUEUED','WAITING','INTERRUPTED','CANCELLED','FAILED')),
            ADD CONSTRAINT fk_sessions_capture_id FOREIGN KEY(capture_id) REFERENCES captures(id)
                ON UPDATE RESTRICT ON DELETE RESTRICT""")
        db.execute("""ALTER TABLE captures
            ADD CONSTRAINT ck_captures_body_object CHECK(jsonb_typeof(body)='object'),
            ADD CONSTRAINT ck_captures_document_id CHECK((body->>'capture_id') IS NOT DISTINCT FROM id)""")
        db.execute("""ALTER TABLE events
            ADD COLUMN created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            ADD CONSTRAINT ck_events_body_object CHECK(jsonb_typeof(body)='object'),
            ADD CONSTRAINT ck_events_kind CHECK(btrim(kind)<>''),
            ADD CONSTRAINT fk_events_session_id FOREIGN KEY(session_id) REFERENCES sessions(id)
                ON UPDATE RESTRICT ON DELETE RESTRICT""")
        db.execute("""ALTER TABLE requests
            ADD COLUMN session_id TEXT GENERATED ALWAYS AS
                (CASE WHEN scope='create' THEN result->>'session_id'
                      WHEN strpos(scope,':')>0 THEN split_part(scope,':',1) END) STORED,
            ADD COLUMN capture_id TEXT GENERATED ALWAYS AS
                (CASE WHEN scope='capture' THEN result->>'capture_id' END) STORED,
            ADD CONSTRAINT ck_requests_result_object CHECK(jsonb_typeof(result)='object'),
            ADD CONSTRAINT ck_requests_identity CHECK(btrim(scope)<>'' AND btrim(id)<>'' AND btrim(fingerprint)<>''),
            ADD CONSTRAINT ck_requests_result_reference CHECK(
                (scope<>'create' OR session_id IS NOT NULL) AND
                (scope<>'capture' OR capture_id IS NOT NULL)),
            ADD CONSTRAINT fk_requests_session_id FOREIGN KEY(session_id) REFERENCES sessions(id)
                ON UPDATE RESTRICT ON DELETE RESTRICT,
            ADD CONSTRAINT fk_requests_capture_id FOREIGN KEY(capture_id) REFERENCES captures(id)
                ON UPDATE RESTRICT ON DELETE RESTRICT""")
        db.execute("""ALTER TABLE page_snapshots
            ADD CONSTRAINT ck_page_snapshots_files_object CHECK(jsonb_typeof(files)='object'),
            ADD CONSTRAINT ck_page_snapshots_revision CHECK(revision>0)""")
        db.execute("CREATE INDEX idx_sessions_capture_id ON sessions(capture_id)")
        db.execute("CREATE INDEX idx_requests_session_id ON requests(session_id)")
        db.execute("CREATE INDEX idx_requests_capture_id ON requests(capture_id)")
        db.execute("ALTER INDEX events_session RENAME TO idx_events_session_id_seq")

    with database.connect(autocommit=True) as db:
        PostgresSaver(db).setup()
    with database.connect() as db:
        db.execute("INSERT INTO page_snapshots(id,files) VALUES(1,'{}')")


@contextmanager
def isolated_database(url):
    database = Database(url, "forj_test_" + uuid4().hex[:16])
    initialize(database)
    try:
        yield database
    finally:
        with psycopg.connect(url, autocommit=True) as db:
            db.execute(sql.SQL("DROP SCHEMA {} CASCADE").format(sql.Identifier(database.schema)))
